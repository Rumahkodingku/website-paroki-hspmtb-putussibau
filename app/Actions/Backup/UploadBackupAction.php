<?php

namespace App\Actions\Backup;

use App\Enums\BackupSource;
use App\Enums\BackupStatus;
use App\Enums\BackupType;
use App\Enums\BackupValidationStatus;
use App\Exceptions\BackupException;
use App\Models\Backup;
use App\Models\User;
use App\Services\AuditLogger;
use App\Services\Backup\BackupStorage;
use Illuminate\Http\UploadedFile;
use Illuminate\Support\Str;
use Throwable;

/**
 * Accepts an external archive into quarantine, validates it, and only then
 * moves it into the archive directory.
 *
 * An uploaded archive never starts a restore. The uploader name is kept as
 * display metadata; the filename on disk is always generated by the server.
 */
final class UploadBackupAction
{
    public function __construct(
        private readonly BackupStorage $storage,
        private readonly ValidateBackupAction $validator,
        private readonly AuditLogger $audit,
    ) {}

    public function handle(UploadedFile $file, User $actor): Backup
    {
        $type = $this->typeFor($file->getClientOriginalName());
        $uuid = (string) Str::uuid();
        $uploadPath = $this->storage->storeUpload($file, $uuid);

        $backup = Backup::query()->create([
            'uuid' => $uuid,
            'type' => $type,
            'source' => BackupSource::Uploaded,
            'status' => BackupStatus::Validating,
            'validation_status' => BackupValidationStatus::Pending,
            'disk' => (string) config('backups.disk'),
            'path' => $uploadPath,
            'original_filename' => $this->safeOriginalName($file->getClientOriginalName()),
            'created_by' => $actor->getKey(),
            'created_by_label' => $actor->name,
            'started_at' => now(),
        ]);

        $local = $this->storage->tempPath(
            $uuid,
            $type === BackupType::Database ? 'upload.sql.gz' : 'upload.zip',
        );
        $archivePath = null;

        try {
            $this->storage->localCopy($uploadPath, $local);
            $this->validator->inspectLocal($backup, $local);
            $checksum = (string) hash_file('sha256', $local);
            $size = (int) filesize($local);
            $filename = $this->storage->suggestedFilename($type, $backup->created_at);
            $archivePath = $this->storage->archivePath($uuid, $filename);

            $this->storage->copyToArchive($uploadPath, $archivePath);

            if (! $this->storage->delete($uploadPath)) {
                throw BackupException::because('storage_unavailable');
            }

            $this->validator->markPassed(
                $backup,
                $checksum,
                $size,
                (string) config('backups.format_version', '1'),
            );

            $backup->forceFill(['path' => $archivePath])->save();

            $this->audit->recordModel(
                'backups',
                'backup_uploaded',
                'success',
                $backup,
                [],
                [],
                [
                    'backup_id' => $backup->uuid,
                    'type' => $backup->type->value,
                    'file_size' => $size,
                ],
                $backup->type->label(),
            );

            return $backup;
        } catch (Throwable $exception) {
            $this->storage->delete($uploadPath);

            if (is_string($archivePath)) {
                $this->storage->delete($archivePath);
            }

            $this->validator->removeLocal($local);

            $safe = $exception instanceof BackupException
                ? $exception
                : BackupException::because('archive_invalid', $exception);

            $this->validator->markFailed($backup, $safe);

            $this->audit->recordModel(
                'backups',
                'backup_upload_rejected',
                'failure',
                $backup,
                [],
                [],
                [
                    'backup_id' => $backup->uuid,
                    'type' => $backup->type->value,
                    'error_code' => $safe->reasonCode,
                ],
                $backup->type->label(),
            );

            throw $safe;
        } finally {
            $this->storage->cleanup($uuid);
        }
    }

    private function typeFor(string $name): BackupType
    {
        $name = strtolower($name);

        if (str_ends_with($name, '.sql.gz')) {
            return BackupType::Database;
        }

        if (str_ends_with($name, '.zip')) {
            return BackupType::Full;
        }

        throw BackupException::because('format_unsupported');
    }

    private function safeOriginalName(string $name): string
    {
        $name = str_replace('\\', '/', $name);
        $name = basename($name);
        $name = (string) preg_replace('/[\x00-\x1F\x7F]/u', '', $name);
        $name = trim($name);

        return Str::limit($name === '' ? 'backup' : $name, 255, '');
    }
}
